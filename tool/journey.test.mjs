import assert from 'node:assert/strict';
import { compareLayout, comparePerf, median, mediaSession } from './journey.mjs';
assert.deepEqual(compareLayout({ Home: { a: [0, 0, 10, 10] } }, { Home: { a: [1, 1, 10, 10] } }), []);
assert.equal(compareLayout({ Home: { a: [0, 0, 10, 10] } }, { Home: { a: [5, 0, 10, 10] } }).length, 1);
assert.match(compareLayout({ Home: { a: [0, 0, 1, 1] } }, { Home: { a: null } })[0], /missing/);
assert.deepEqual(comparePerf({ g: { worst: 20, lt: 0 } }, { g: { worst: 24, lt: 1 } }), []);
assert.equal(comparePerf({ g: { worst: 20, lt: 0 } }, { g: { worst: 40, lt: 0 } }).length, 1);
assert.equal(comparePerf({ g: { worst: 20, lt: 0 } }, { g: { worst: 20, lt: 3 } }).length, 1);
assert.equal(median([3, 1, 2]), 2);
const dump = 'x\n SUMMARY: package=other\n  state=PlaybackState {state=PAUSED(2)}\n SUMMARY: package=io.github.jacob_e_lee.taro_music, uid=1\n state=PlaybackState {state=PLAYING(3)}\n metadata: size=4, description=Cry For Me (1 Hour, x), The Weeknd, null\n SUMMARY: package=zzz\n state=PLAYING';
assert.deepEqual(mediaSession(dump), { playing: true, title: 'Cry For Me (1 Hour, x)' });
console.log('ok');
